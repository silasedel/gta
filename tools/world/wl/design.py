def _paloma():
    ax, az, bx, bz = 720.0, 4620.0, -320.0, 6520.0
    L = _m.hypot(bx - ax, bz - az)
    ux, uz = (bx - ax) / L, (bz - az) / L
    px, pz = -uz, ux                       # toward the ocean (east / south-east) side
    prof = [(0.0, 0), (0.04, 95), (0.12, 150), (0.25, 185), (0.4, 205), (0.52, 170), (0.65, 195), (0.8, 180), (0.92, 120), (1.0, 0)]
    east = [(ax + ux * L * t + px * w * (1.0 + 0.12 * _m.sin(t * 9)), az + uz * L * t + pz * w * (1.0 + 0.12 * _m.sin(t * 9))) for t, w in prof]
    west = [(ax + ux * L * t - px * w * (0.92 + 0.14 * _m.cos(t * 7)), az + uz * L * t - pz * w * (0.92 + 0.14 * _m.cos(t * 7))) for t, w in prof[1:-1]]
    return east + west[::-1]


