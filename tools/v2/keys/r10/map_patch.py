# r10 (playtest Nov 19: the canal on the pause map / minimap looked like a high heel): the published map build predates the r8 / r9 carve
# (tools/v2/map3/keys_detail.py carve_nico), so its Keys land ring still has the old canal notch. This writes the land ring as the next
# build will carve it (same shapes as carve_nico: the lot block, the 12 m canal, the bay beyond the bulkhead) for the ONE land polygon
# around Nico's lot, plus a fingerprint of the old ring; nicoHouse.v2.js swaps it into game.city.mapLayers only if the fingerprint matches
# (a rebuilt map carries the carve itself and is left alone).
#   python3 tools/v2/keys/r10/map_patch.py public/assets/miami/<build>/map.json
import json, math, sys
from shapely.geometry import Polygon, Point
m = json.load(open(sys.argv[1])); q = m['q']
L = json.load(open('public/assets/world/layout.json')); sp = L.get('setpieces') or L['data']['setpieces']
spot = sp['nico_house'] if isinstance(sp, dict) else [s for s in sp if s.get('id') == 'nico_house'][0]
h = spot['heading']; ox, oz = spot['x'], spot['z']; th = math.pi / 4 - h; c2, s2 = math.cos(th), math.sin(th); OZ = 4.5
def H(x, z):
    dx, dz = x, z + 7.0; sx, sz = dx * c2 + dz * s2, -7.0 - dx * s2 + dz * c2; sz += OZ
    c, s = math.cos(h), math.sin(h); return (ox + sx * c + sz * s, oz - sx * s + sz * c)
poly = lambda pts: Polygon([H(x, z) for x, z in pts])
block = poly(((-27, -60), (62, -60), (62, 34), (-27, 34)))
bay = poly(((-27, -60), (62, -60), (62, -16.5), (-27, -16.5)))
canal = poly(((12.6, -17.5), (24.6, -17.5), (24.6, 20.0), (12.6, 20.0)))
shore = poly(((-27, -16.5), (62, -16.5), (62, 34), (-27, 34))).difference(canal)
house = Point(H(0, -7))
for i, it in enumerate(m['land']):
    p = it['p']; ring = [(p[k] / q, p[k + 1] / q) for k in range(0, len(p), 2)]
    if it.get('ho') or not Polygon(ring).buffer(0).contains(house): continue
    g = Polygon(ring).buffer(0).difference(block).union(shore).difference(bay).buffer(0)
    if g.geom_type != 'Polygon': g = max(g.geoms, key=lambda a: a.area)
    xs = [a for a, _ in ring]; zs = [b for _, b in ring]
    out = dict(note='generated by tools/v2/keys/r10/map_patch.py', old=dict(n=len(ring), bbox=[round(min(xs), 1), round(min(zs), 1), round(max(xs), 1), round(max(zs), 1)]),
               outer=[[round(a, 2), round(b, 2)] for a, b in list(g.exterior.coords)[:-1]], holes=[[[round(a, 2), round(b, 2)] for a, b in list(r.coords)[:-1]] for r in g.interiors])
    open('src/world/setpieces/nicoHouse/mapPatch.data.js', 'w').write('// r10: the Keys land ring around Nico\'s lot as carved (see tools/v2/keys/r10/map_patch.py); swapped in by nicoHouse.v2.js\nexport const NICO_MAP_LAND = ' + json.dumps(out) + ';\n')
    print('land', i, 'old', len(ring), 'new', len(out['outer']), 'holes', len(out['holes'])); break
