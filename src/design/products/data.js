import { getBrand } from '../brands/index.js';
const SOLD = {
  drink: ['convenience', 'fuel', 'supermarket', 'pharmacy'],
  alcohol: ['liquor-store', 'bar', 'supermarket', 'convenience'],
  snack: ['convenience', 'fuel', 'supermarket', 'pharmacy'],
  food: ['fast-food', 'cuban-cafe', 'street-vendor'],
  phone: ['electronics-store', 'carrier'],
  shoes: ['shoe-store'],
  pharmacy: ['pharmacy', 'supermarket', 'convenience'],
  tobacco: ['convenience', 'fuel', 'smoke-shop'],
  lottery: ['convenience', 'fuel'],
  pantry: ['supermarket', 'convenience'],
};
const fx = (n, cat, junk) => {
  const e = [];
  if (n.kcal)
    e.push(
      { type: 'heal', amount: Math.round(n.kcal / (junk ? 40 : 22)) },
      { type: 'stamina', amount: Math.round(n.kcal / 30) },
    );
  if (n.caffeine)
    e.push({
      type: 'sprint',
      amount: Math.min(1, n.caffeine / 200),
      seconds: Math.round(20 + n.caffeine / 3),
    });
  if (n.alcohol)
    e.push({
      type: 'drunk',
      amount: +(n.alcohol / 14).toFixed(2),
      seconds: Math.round(n.alcohol * 12),
    });
  if (cat === 'drink' && !n.alcohol) e.push({ type: 'hydrate', amount: 1 });
  return e;
};
const P = (id, name, brand, cat, price, model, modelOpts = {}, n = null, x = {}) => {
  const [category, sub] = cat.split('/');
  const b = getBrand(brand);
  const junk = x.junk ?? ['snack'].includes(category) ?? false;
  return {
    id,
    name,
    brand,
    category,
    sub,
    tier: x.tier || b?.tier || 'mid',
    price,
    model,
    modelOpts,
    nutrition: n,
    effects: n ? fx(n, category, junk) : [],
    junk,
    bites: x.bites || 0,
    sips: x.sips || 0,
    states:
      x.states ||
      (model === 'can' || model === 'bottle' || model === 'cup' ? ['closed', 'open'] : ['closed']),
    soldAt: x.soldAt || SOLD[category] || ['convenience'],
    shelf:
      x.shelf ||
      (category === 'drink' || category === 'alcohol'
        ? 'cooler'
        : category === 'food'
          ? 'hot-case'
          : 'shelf'),
    hold:
      x.hold ||
      (model === 'can' || model === 'bottle' ? 'bottle' : model === 'cup' ? 'cup' : 'hand'),
    size: x.size || null,
    weight: x.weight || null,
    tags: x.tags || [],
    ...(x.wear ? { wear: x.wear } : {}),
  };
};
