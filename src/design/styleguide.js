export const styleguide = {
  districts: DISTRICT_STYLES,
  tiers: TIER_STYLES,
  district(id) {
    return DISTRICT_STYLES[id] || null;
  },
  tier(id) {
    return TIER_STYLES[id] || TIER_STYLES.mid;
  },
  // An interior scheme for a brand's own store: tier defaults tinted with the brand palette.
  forBrand(brand, district) {
    const t = TIER_STYLES[brand.tier] || TIER_STYLES.mid,
      d = district ? DISTRICT_STYLES[district] : null;
    const pick = (list) => list[brand.seed % list.length];
    return {
      floor: pick(d && brand.presence === 'local' ? d.floors : t.floors),
      walls: pick(d && brand.presence === 'local' ? d.walls : t.finishes),
      counter:
        brand.tier === 'luxury'
          ? 'stone_granite_black'
          : brand.tier === 'budget'
            ? 'laminate_woodgrain'
            : 'laminate_white',
      trim: brand.tier === 'luxury' ? 'metal_brass' : 'metal_brushed_steel',
      accent: brand.palette.primary,
      accent2: brand.palette.secondary,
      neon: brand.palette.neon,
      lighting: t.lighting,
      fixtures: t.fixtures,
      density: t.density,
      sign: brand.signStyle.type,
      service: t.service,
      uniform: { shirt: brand.palette.primary, trim: brand.palette.secondary, logo: brand.id },
    };
  },
};
