// Product and brand catalog used by the interiors engine.
// Source of truth is the design system (src/design, game.design). Until a brand or product exists there, the PROVISIONAL entries
// registered below (and by store types) are used; they are flagged prov: true and are replaced automatically once the design
// system defines the same id. Store types register their own products with registerProducts().
import { GLOBAL } from '../kit/atlas.js';
import { formGeometry, formDef } from './forms.js';
import { paintCell } from './labels.js';

const BRANDS = new Map(),
  PRODUCTS = new Map();
let design = null;
export function setDesign(d) {
  design = d || null;
}
export const getDesign = () => design;
export function registerBrands(list) {
  for (const b of list) BRANDS.set(b.id, { prov: true, palette: {}, ...b });
}
export function registerProducts(list) {
  for (const p of list) PRODUCTS.set(p.id, { prov: true, params: {}, ...p });
}
export function getBrand(id) {
  try {
    const b = design?.getBrand?.(id);
    if (b) return b;
  } catch (e) {
    /* */
  }
  return BRANDS.get(id) || BRANDS.get('generic');
}
export function getProduct(id) {
  const p = PRODUCTS.get(id);
  if (!p) return null;
  try {
    const d = design?.getProduct?.(id);
    if (d)
      return {
        ...p,
        name: d.name || p.name,
        price: d.price ?? p.price,
        nutrition: d.nutrition || p.nutrition,
        effects: d.effects || p.effects,
        design: d,
        prov: false,
      };
  } catch (e) {
    /* */
  }
  return p;
}
export const allProducts = () => [...PRODUCTS.values()];
export const productsWhere = (fn) => [...PRODUCTS.values()].filter(fn);
export function productGeometry(id) {
  const p = PRODUCTS.get(id);
  return formGeometry(p.form, p.params);
}
export function productCell(id) {
  const p = PRODUCTS.get(id),
    f = formDef(p.form),
    px = f.px || 128,
    w = Math.round(px * (f.aspect || 1.5)),
    h = Math.round(px / 0.8);
  return GLOBAL.cell('prod:' + id, w, h, (g, cw, ch) => paintCell(g, cw, ch, p, getBrand(p.brand)));
}
export function productSize(id) {
  return productGeometry(id).userData.size;
}

