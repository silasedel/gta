export function themeFor(type, sf, seed) {
  const list = BY_TYPE[type];
  if (!list) return null;
  const hint = HINT[(sf.cuisine || '').toLowerCase()] || HINT[(sf.kind || '').toLowerCase()];
  const r = srng(seed * 7 + 13);
  const key = hint && THEMES[hint]?.types.includes(type) ? hint : pick(r, list);
  const T = THEMES[key];
  const rr = srng(seed * 11 + 5);
  const name = sf.name || `${pick(rr, T.name[0])} ${pick(rr, T.name[1])}`.replace(/\s+&\s+&/, ' &');
  // per-venue variation inside the theme
  const shift = (hex, k) => {
    const h = hex >>> 0;
    const r0 = (h >> 16) & 255,
      g0 = (h >> 8) & 255,
      b0 = h & 255;
    const f = 0.86 + k * 0.28;
    return (
      (Math.min(255, (r0 * f) | 0) << 16) |
      (Math.min(255, (g0 * f) | 0) << 8) |
      Math.min(255, (b0 * f) | 0)
    );
  };
  const v = rr();
  return {
    key,
    ...T,
    name,
    wall: pick(rr, T.walls),
    floorStyle: pick(rr, T.floor),
    pal: {
      ...T.palette,
      accent: shift(T.palette.accent, v),
      fabric: shift(T.palette.fabric, 1 - v),
    },
    variant: Math.floor(rr() * 4),
  };
}

// ---- shops: per-store colour scheme + fixture style + sign style ----
const SHOP_SCHEMES = [
  { wall: 'plaster', shelf: 0xf4f4f0, trim: 0x2a9d8f },
  { wall: 'whitebrick', shelf: 0x2b2b30, trim: 0xe76f51 },
  { wall: 'woodPanel', shelf: 0x8a5a3a, trim: 0x1d3557 },
  { wall: 'subway', shelf: 0xd8dde3, trim: 0xd62828 },
  { wall: 'concrete', shelf: 0x1c1c22, trim: 0xffb703 },
  { wall: 'stripe', shelf: 0xffffff, trim: 0x7b2cbf },
  { wall: 'plaster', shelf: 0xc8a97e, trim: 0x2d6a4f },
  { wall: 'wallpaperPalm', shelf: 0xf1faee, trim: 0x2a7de1 },
];
export function shopStyle(type, seed) {
  const r = srng(seed * 3 + 101);
  const s = pick(r, SHOP_SCHEMES);
  return {
    ...s,
    shelfStyle: pick(r, ['metal', 'wood', 'white']),
    signStyle: pick(r, ['neon', 'box', 'script']),
    variant: Math.floor(r() * 4),
  };
}
