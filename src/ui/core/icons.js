export function icon(name, o = {}) {
  const d = ICONS[name] || [c(12, 12, 3)];
  const sw = o.stroke ? ` stroke-width="${o.stroke}"` : '';
  return (
    SVG_OPEN.replace(' aria-hidden', sw + ' aria-hidden') +
    (d[0] ? `<path d="${d[0]}"/>` : '') +
    (d[1] ? `<path d="${d[1]}" fill="currentColor" stroke="none"/>` : '') +
    '</svg>'
  );
}
export function iconEl(name, cls = 'ps-ico') {
  const s = document.createElement('span');
  s.className = cls;
  s.innerHTML = icon(name);
  return s;
}
export const hasIcon = (name) => !!ICONS[name];

const pathCache = new Map();
/** Draw an icon on a 2D canvas, centered on (x, y). */
export function drawIcon(g, name, x, y, size = 16, color = '#fff', lineWidth = 1.8) {
  const d = ICONS[name];
  if (!d) return false;
  let p = pathCache.get(name);
  if (!p) {
    p = [d[0] ? new Path2D(d[0]) : null, d[1] ? new Path2D(d[1]) : null];
    pathCache.set(name, p);
  }
  const k = size / 24;
  g.save();
  g.translate(x - size / 2, y - size / 2);
  g.scale(k, k);
  g.lineCap = 'round';
  g.lineJoin = 'round';
  g.lineWidth = lineWidth;
  g.strokeStyle = color;
  g.fillStyle = color;
  if (p[0]) g.stroke(p[0]);
  if (p[1]) g.fill(p[1]);
  g.restore();
  return true;
}

